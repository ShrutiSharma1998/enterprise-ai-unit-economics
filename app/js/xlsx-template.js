// Builds the pre-filled Excel template for detailed input, and reads a filled-in one back.
// Building and parsing work on plain arrays (AOA: array of rows of cells) and have no dependency on the
// SheetJS library, so app/tests/template.test.js can check them without touching a real .xlsx file. The
// download and upload functions at the bottom need the vendored SheetJS library (js/vendor/xlsx.full.min.js)
// and only run in the browser.
(function (root, factory) {
  if (typeof module === "object" && module.exports) module.exports = factory();
  else root.Template = factory();
}(typeof self !== "undefined" ? self : this, function () {
  "use strict";

  // The UMD wrapper's own "root" parameter belongs to the outer function, not to this factory function, so the
  // global object (for the vendored SheetJS library, window.XLSX) is found again here.
  var GLOBAL = (typeof window !== "undefined") ? window : (typeof self !== "undefined") ? self : (typeof global !== "undefined") ? global : {};
  const SHEET_NAMES = { readme: "Read me", org: "Org", teams: "Teams", enterprise: "Enterprise costs", prices: "Price book" };
  const SHEET_ORDER = ["readme", "org", "teams", "enterprise", "prices"];
  const ORG_SELECTS = { shape: ["Centralized", "Federated", "Hub-and-spoke"], alloc: ["Usage-proportional", "Headcount proxy", "Even split", "Central budget"] };
  const NUMERIC_ORG = ["horizon", "pd_rate", "hours_day", "work_days", "obs_per_out"];
  const ORG_HEADER = ["Key", "Field", "Value", "Allowed values or unit"];
  const TEAMS_HEADER = ["Key", "Label", "Allowed values or unit"];

  // ---------- building (pure; no SheetJS needed)

  function readmeSheet(D) {
    return [
      ["AI unit economics calculator: data template (preview " + D.meta.version.split(" ")[0] + ")"],
      [""],
      ["This file was generated by the calculator with your current inputs already filled in. Add detail, then upload it back."],
      [""],
      ["Only edit the Value column on the Org and Enterprise costs sheets, and the team columns on the Teams sheet."],
      ["Do not rename the Read me, Org, Teams or Enterprise costs sheets, and do not edit column A (Key) on any sheet: the upload reads column A to know which row is which, in any row order."],
      ["Rows with an unrecognised key are ignored with a warning. A blank cell uses the team type's starter value instead of an error, except for the fields marked required below."],
      ["Required on every team column: Archetype (team type), Buying model, Licensed users, Active share of licensed users at plateau, Outcome basis, Minutes saved per outcome."],
      ["Price fields (seat prices, models, tools, parsing, embeddings, index plan and storage) take an ID from the Price book sheet, typed exactly as shown there."],
      ["To add a team, copy an existing team's whole column into the blank column at the right and change its values. There is no fixed limit on the number of teams."],
      ["Percent fields are entered as a number from 0 to 100, not a fraction."],
      [""],
      ["Nothing in this file is sent anywhere until you choose to upload it back to the calculator running in your own browser."],
    ];
  }

  function orgSheet(state, D) {
    const rows = [ORG_HEADER];
    rows.push(["name", "Organization name", state.orgName, "text"]);
    for (const key of D.template.orgFields) {
      if (key === "name") continue;
      const f = D.orgFields[key];
      const allowed = ORG_SELECTS[key] ? ORG_SELECTS[key].join(" / ") : f.unit;
      rows.push([key, f.label, state.org[key], allowed]);
    }
    return rows;
  }

  function enterpriseSheet(state, D) {
    const rows = [ORG_HEADER];
    for (const key of D.template.enterpriseFields) {
      const p = D.params[key];
      rows.push([key, p.desc + " (" + p.line + ")", state.entered[key] || 0, p.unit]);
    }
    return rows;
  }

  function formatFieldValue(key, m, value) {
    if (m.kind === "percent") return Math.round(value * 10000) / 100;
    if (m.kind === "toggle") return value;
    return value;
  }

  function teamsSheet(state, D) {
    const order = D.template.teamFieldOrder;
    const teams = state.teams.map((t, i) => ({ label: (t.name && t.name.trim()) || "Team " + (i + 1), data: t }));
    teams.push({ label: "Add a team here: copy an existing column, paste it in the next column, then edit it", data: {} });
    const header = TEAMS_HEADER.concat(teams.map((t) => t.label));
    const rows = [header];
    for (const key of order) {
      const m = D.fields[key];
      const allowed = m.kind === "select" ? m.options.join(" / ")
        : m.kind === "toggle" ? "1 / 0"
        : m.kind === "percent" ? "% (0 to 100)"
        : m.kind === "price" ? "ID from the Price book sheet" + (m.allowNone ? " (or blank)" : "")
        : m.unit || "text";
      const row = [key, m.label, allowed];
      for (const t of teams) row.push(t.data[key] === undefined ? "" : formatFieldValue(key, m, t.data[key]));
      rows.push(row);
    }
    return rows;
  }

  function priceLabel(r) {
    const tag = r.status !== "standard" ? " (" + r.status + (r.to ? " until " + r.to : "") + ")" : "";
    return r.provider + " " + r.product + tag;
  }

  function pricesSheet(D) {
    const rows = [["ID", "Product", "Price", "Unit", "Source", "Fetched"]];
    for (const r of D.pricebook) {
      const price = r.kind === "Model" ? r.p_in + " in / " + r.p_out + " out" : String(r.p_in);
      rows.push([r.id, priceLabel(r), price, r.unit, r.src, D.meta.priceDate]);
    }
    return rows;
  }

  function buildAOA(state, D) {
    return {
      readme: readmeSheet(D), org: orgSheet(state, D), teams: teamsSheet(state, D),
      enterprise: enterpriseSheet(state, D), prices: pricesSheet(D),
    };
  }

  // ---------- parsing (pure; takes the same shape SheetJS's sheet_to_json(ws, {header:1}) returns)

  const blankRow = (row) => !row || row.every((c) => c === "" || c === null || c === undefined);
  const cellStr = (v) => (v === undefined || v === null ? "" : String(v).trim());

  function keyMap(rows, valueCol) {
    const map = {};
    for (let r = 1; r < (rows || []).length; r++) {
      const row = rows[r];
      if (blankRow(row)) continue;
      const key = cellStr(row[0]);
      if (key) map[key] = row[valueCol];
    }
    return map;
  }

  function checkShape(sheets) {
    if (!sheets.readme) return "This file has no 'Read me' sheet, so it does not look like a template from this calculator. Download a fresh template and copy your edits into it.";
    if (!sheets.org || !rowsEqual(sheets.org[0], ORG_HEADER)) return "The Org sheet's header row has changed, so the file cannot be read safely. Download a fresh template and copy your edits into it.";
    if (!sheets.teams || !rowsEqual((sheets.teams[0] || []).slice(0, 3), TEAMS_HEADER)) return "The Teams sheet's header row has changed, so the file cannot be read safely. Download a fresh template and copy your edits into it.";
    return null;
  }
  function rowsEqual(a, b) {
    return Array.isArray(a) && a.length >= b.length && b.every((v, i) => cellStr(a[i]) === v);
  }

  function parseOrg(rows, D, errors, warnings) {
    const map = keyMap(rows, 2);
    let orgName = D.meta.org.name;
    if ("name" in map) { const v = cellStr(map.name); if (v) orgName = v; }
    else warnings.push("Org sheet: no 'name' row found; kept the current organization name.");
    const org = {};
    for (const key of ["shape", "alloc"]) {
      if (!(key in map)) { errors.push("Org sheet: missing required row '" + key + "'."); continue; }
      const v = cellStr(map[key]);
      if (!ORG_SELECTS[key].includes(v)) { errors.push("Org sheet, " + key + ": '" + v + "' is not one of " + ORG_SELECTS[key].join(", ") + "."); continue; }
      org[key] = v;
    }
    for (const key of NUMERIC_ORG) {
      if (!(key in map)) { errors.push("Org sheet: missing required row '" + key + "'."); continue; }
      const n = Number(map[key]);
      if (!Number.isFinite(n) || n < 0) { errors.push("Org sheet, " + key + ": '" + map[key] + "' is not a positive number."); continue; }
      if (key === "horizon" && n > D.meta.horizonMax) { errors.push("Org sheet, horizon: " + n + " is above the maximum of " + D.meta.horizonMax + " months."); continue; }
      org[key] = key === "horizon" ? Math.round(n) : n;
    }
    return { orgName, org };
  }

  function parseEnterprise(rows, D, errors) {
    const map = keyMap(rows, 2);
    const entered = {};
    for (const key of D.template.enterpriseFields) {
      const raw = key in map ? map[key] : 0;
      const n = cellStr(raw) === "" ? 0 : Number(raw);
      if (!Number.isFinite(n) || n < 0) { errors.push("Enterprise costs sheet, " + key + ": '" + raw + "' is not a positive number."); continue; }
      entered[key] = n;
    }
    return entered;
  }

  function parseFieldValue(m, raw, D, label, errors) {
    if (m.kind === "select") {
      const v = cellStr(raw);
      if (!m.options.includes(v)) { errors.push(label + ", " + m.label + ": '" + v + "' is not one of " + m.options.join(", ") + "."); return undefined; }
      return v;
    }
    if (m.kind === "price") {
      const v = cellStr(raw);
      if (m.allowNone && v === "") return "";
      const rec = D.pricebook.find((r) => r.id === v);
      if (!rec || rec.kind !== m.priceKind) { errors.push(label + ", " + m.label + ": '" + v + "' is not a known price ID on the Price book sheet."); return undefined; }
      return v;
    }
    if (m.kind === "toggle") {
      const n = Number(raw);
      if (n !== 0 && n !== 1) { errors.push(label + ", " + m.label + ": must be 1 or 0."); return undefined; }
      return n;
    }
    if (m.kind === "text") return cellStr(raw);
    const n = Number(raw);
    if (!Number.isFinite(n)) { errors.push(label + ", " + m.label + ": '" + raw + "' is not a number."); return undefined; }
    if (m.kind === "percent") {
      if (n < 0 || n > 100) { errors.push(label + ", " + m.label + ": " + n + "% must be between 0 and 100."); return undefined; }
      return n / 100;
    }
    if (n < 0) { errors.push(label + ", " + m.label + ": " + n + " cannot be negative."); return undefined; }
    return n;
  }

  function parseTeams(rows, D, errors, warnings) {
    if (!rows || rows.length < 2) { errors.push("Teams sheet: no rows found."); return []; }
    const header = rows[0];
    const byKey = {};
    for (let r = 1; r < rows.length; r++) {
      const row = rows[r];
      if (blankRow(row)) continue;
      const key = cellStr(row[0]);
      if (!key) continue;
      if (key !== "name" && !D.fields[key]) { warnings.push("Teams sheet: unknown row '" + key + "' ignored."); continue; }
      byKey[key] = row;
    }
    const results = [];
    for (let col = 3; col < header.length; col++) {
      const anyValue = Object.keys(byKey).some((k) => cellStr(byKey[k][col]) !== "");
      if (!anyValue) continue;   // an unused extra column, such as the "copy this column" guide left untouched
      const label = "Team column " + (col - 2) + (cellStr(header[col]) ? " (" + cellStr(header[col]) + ")" : "");
      const archRaw = byKey.archetype ? cellStr(byKey.archetype[col]) : "";
      const code = Object.keys(D.archetypes).find((c) => archRaw === D.archetypes[c].label || archRaw === c);
      if (!code) { errors.push(label + ", Archetype: '" + archRaw + "' does not match a team type. Use one of: " + Object.keys(D.archetypes).map((c) => D.archetypes[c].label).join("; ") + "."); continue; }
      const preset = JSON.parse(JSON.stringify(D.archetypes[code].preset));
      const team = Object.assign({ name: "", bu: "", licensed: 500 }, preset, { archetype: D.archetypes[code].label, active: 1 });
      const edited = {};
      let teamErrors = 0;
      for (const key of D.template.teamFieldOrder) {
        if (key === "archetype") continue;
        const m = D.fields[key];
        const cellRow = byKey[key];
        const raw = cellRow ? cellRow[col] : undefined;
        if (cellStr(raw) === "") {
          if (m.kind === "price" && m.allowNone) {
            team[key] = "";   // blank is itself a valid choice for this field: no vendor price, priced per token
            if (preset[key] !== "") edited[key] = true;
          } else if (D.template.requiredTeamFields.includes(key)) {
            errors.push(label + ", " + m.label + ": required, and blank.");
            teamErrors++;
          } else {
            warnings.push(label + ", " + m.label + ": blank, used the " + D.archetypes[code].label + " starter value.");
          }
          continue;
        }
        const parsed = parseFieldValue(m, raw, D, label, errors);
        if (parsed === undefined) { teamErrors++; continue; }
        team[key] = parsed;
        if (JSON.stringify(parsed) !== JSON.stringify(preset[key])) edited[key] = true;
      }
      if (team.basis === "per user" && !(D.fields.o_user && "o_user" in team && team.o_user > 0) && !(byKey.o_user && cellStr(byKey.o_user[col]) !== "")) {
        warnings.push(label + ": outcome basis is 'per user' but outcomes per active user is 0; the team will cost nothing to run.");
      }
      if (team.basis === "direct volume" && !(team.direct > 0) && !(byKey.direct && cellStr(byKey.direct[col]) !== "")) {
        warnings.push(label + ": outcome basis is 'direct volume' but outcomes per month is 0; the team will cost nothing to run.");
      }
      if (teamErrors) continue;
      results.push({ team, edited });
    }
    if (!results.length && !errors.length) errors.push("Teams sheet: no team columns with data were found.");
    return results;
  }

  function parseAOA(sheets, D) {
    const errors = [], warnings = [];
    const shapeError = checkShape(sheets);
    if (shapeError) return { errors: [shapeError], warnings: [], org: null, orgName: null, entered: null, teams: [] };
    const { orgName, org } = parseOrg(sheets.org, D, errors, warnings);
    const entered = parseEnterprise(sheets.enterprise || [], D, errors);
    const teams = parseTeams(sheets.teams, D, errors, warnings);
    return { orgName, org, entered, teams, errors, warnings };
  }

  // ---------- browser-only: needs the vendored SheetJS library (js/vendor/xlsx.full.min.js)

  function download(state, D, filename) {
    const XLSX = GLOBAL.XLSX;
    if (!XLSX) throw new Error("The spreadsheet library did not load.");
    const sheets = buildAOA(state, D);
    const wb = XLSX.utils.book_new();
    for (const key of SHEET_ORDER) XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(sheets[key]), SHEET_NAMES[key]);
    XLSX.writeFile(wb, filename);
  }

  function readFile(file) {
    const XLSX = GLOBAL.XLSX;
    if (!XLSX) return Promise.reject(new Error("The spreadsheet library did not load."));
    return file.arrayBuffer().then((buf) => {
      const wb = XLSX.read(buf, { type: "array" });
      const sheets = {};
      for (const key of SHEET_ORDER) {
        const name = SHEET_NAMES[key];
        if (wb.Sheets[name]) sheets[key] = XLSX.utils.sheet_to_json(wb.Sheets[name], { header: 1, defval: "", raw: true });
      }
      return sheets;
    });
  }

  return { SHEET_NAMES, SHEET_ORDER, buildAOA, parseAOA, download, readFile };
}));
